"""Separate a fresh raw-input experiment from explicit same-run continuation."""
import hashlib
import json
import os
from pathlib import Path
import uuid

from .io import dump, require

POLICY = "raw_downloads_only_v1"
MARKER = "fresh_run.json"


def code_identity(root):
    root = Path(root)
    paths = [root / n for n in ("run.py", "config.json", "requirements.txt")]
    if (root / 'reproduce_from_public.py').is_file():
        paths.append(root / 'reproduce_from_public.py')
    if (root / 'requirements-supplementary.txt').is_file():
        paths.append(root / 'requirements-supplementary.txt')
    for folder in ("pipeline", "analysis", "tests", "inputs"):
        paths.extend(p for p in (root / folder).rglob("*") if p.suffix in (".py", ".R", ".json", ".csv"))
    digest = hashlib.sha256()
    for path in sorted(paths):
        digest.update(path.relative_to(root).as_posix().encode())
        digest.update(path.read_bytes())
    return digest.hexdigest()


def assert_code(root, expected):
    require(code_identity(root) == expected,
            'Source code/settings changed during execution. Do not edit a running release.')


def claim(out, component, resume=False, parent_id=None, code=None):
    """Call while holding the component lock; do not adopt older output trees."""
    out = Path(out).resolve()
    marker = out / MARKER
    if marker.exists():
        old = json.loads(marker.read_text(encoding="utf-8"))
        require(resume, "Output already belongs to an experiment. Use a NEW output, or --resume for this run only.")
        require(old.get("policy") == POLICY and old.get("component") == component,
                "This is not a raw-input experiment of the current component.")
        require(old.get("output") == str(out), "Copied/moved result trees cannot be resumed as a fresh experiment.")
        require(parent_id is None or old.get("run_id") == parent_id, "Upstream and downstream run identities differ.")
        require(code is None or old.get("code") == code, "Code/settings changed. Start a NEW output directory.")
        return old["run_id"]
    require(not resume, "--resume requires a fresh_run.json from this runner, not an old result directory.")
    other = [p.name for p in out.iterdir() if p.name != "run.lock"] if out.exists() else []
    require(not other, "Fresh execution requires an empty output; old data/results will not be imported: " + str(other[:8]))
    out.mkdir(parents=True, exist_ok=True)
    run_id = parent_id or str(uuid.uuid4())
    dump(marker, {"run_id": run_id, "component": component, "policy": POLICY,
                  "output": str(out), "code": code})
    return run_id


def current_source(source, expected_id=None):
    source = Path(source).resolve()
    marker = source / MARKER
    require(marker.is_file(), "Source must be generated by the fresh raw-input core, not imported prepared data.")
    record = json.loads(marker.read_text(encoding="utf-8"))
    require(record.get("policy") == POLICY and record.get("component") == "core"
            and record.get("output") == str(source), "Invalid raw-input source identity.")
    require(expected_id is None or record.get("run_id") == expected_id,
            "Cannot use another experiment's prepared inputs.")
    return record["run_id"]


def parent_run():
    return os.environ.get("PAPER1_FRESH_RUN_ID")
