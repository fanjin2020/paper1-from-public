def generate(root):
    root = Path(root).resolve()
    with rows(root/'source_index.csv') as reader:
        header = next(reader); index = [dict(zip(header,row)) for row in reader]
    sources = {r['file']:r for r in index}
    require(len(sources)==len(index),'Duplicate table source paths')
    with rows(root/'block_sources.csv') as reader:
        header = next(reader); mapping = [dict(zip(header,row)) for row in reader]
    require(len(mapping)==len(EXPECTED_BLOCKS) and {r['block'] for r in mapping}==EXPECTED_BLOCKS,
            'Workbook requires all 112 unique blocks')
    declared = {(b,r['file']) for r in index for b in r['blocks'].split(',') if b}
    require({(r['block'],r['file']) for r in mapping}==declared,'Workbook mapping differs from source index')
    entries = []
    for record in sorted(mapping,key=lambda r:tuple(map(int,r['block'][1:].split('.')))):
        require(record['file'] in sources,'Unindexed workbook source')
        src = sources[record['file']]; path = source_path(root,record['file'])
        require(path.stat().st_size==int(src['bytes']) and sha(path)==src['sha256'],'Changed workbook source: '+record['file'])
        with rows(path) as reader:
            fields = next(reader)
        require(fields and len(fields)<=16384,'Invalid table column count')
        entries.append(dict(record,path=path,header=fields,rows=int(src['rows']),
                            sheet=int(record['block'][1:].split('.')[0])))
    for sid in range(1,21):
        start = 120 if sid==1 else 6
        for entry in (e for e in entries if e['sheet']==sid):
            entry['start'] = start
            entry['header_row'] = start+4
            start = entry['header_row']+entry['rows']+4
        require(start<=1048576,'Worksheet exceeds Excel row limit')
    catalog = [[e['block'],f"S{e['sheet']:02}",str(e['rows']),str(e['header_row']),str(len(e['header']))] for e in entries]
    target = root/'Supplementary_Tables.xlsx'
    temp = root/'Supplementary_Tables.xlsx.tmp'
    require(not temp.exists(),'Unfinished workbook export exists: '+str(temp))
    try:
        with ZipFile(temp,'w',compression=ZIP_DEFLATED,compresslevel=6) as z:
            content = '<?xml version="1.0"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/>'
            content += '<Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/><Override PartName="/xl/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml"/>'
            content += ''.join(f'<Override PartName="/xl/worksheets/sheet{i}.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>' for i in range(1,21))+'</Types>'
            z.writestr('[Content_Types].xml',content)
            z.writestr('_rels/.rels','<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="'+REL+'/officeDocument" Target="xl/workbook.xml"/></Relationships>')
            z.writestr('xl/workbook.xml',f'<workbook xmlns="{NS}" xmlns:r="{REL}"><sheets>'+''.join(f'<sheet name="S{i:02}" sheetId="{i}" r:id="rId{i}"/>' for i in range(1,21))+'</sheets></workbook>')
            z.writestr('xl/_rels/workbook.xml.rels','<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'+''.join(f'<Relationship Id="rId{i}" Type="{REL}/worksheet" Target="worksheets/sheet{i}.xml"/>' for i in range(1,21))+f'<Relationship Id="rId21" Type="{REL}/styles" Target="styles.xml"/></Relationships>')
            z.writestr('xl/styles.xml',STYLES)
            for sid in range(1,21):
                blocks = [e for e in entries if e['sheet']==sid]
                last = blocks[-1]['header_row']+blocks[-1]['rows']
                cols = max(5,max(len(e['header']) for e in blocks))
                merges = ['A1:E1','A2:E2','A3:E3']
                with z.open(f'xl/worksheets/sheet{sid}.xml','w',force_zip64=True) as out:
                    def emit(data): out.write(data.encode('utf-8'))
                    emit(f'<worksheet xmlns="{NS}"><dimension ref="A1:{column(cols)}{last}"/><sheetViews><sheetView workbookViewId="0" showGridLines="0"><pane ySplit="3" topLeftCell="A4" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews><sheetFormatPr defaultRowHeight="20"/><cols><col min="1" max="1" width="28" customWidth="1"/><col min="2" max="{cols}" width="22" customWidth="1"/></cols><sheetData>')
                    emit(row_xml(1,[f'Table S{sid} '+TITLES[sid-1]],1,26,False))
                    emit(row_xml(2,['Complete results; blank numerical cells are unavailable, not zero.'],2,24,False))
                    emit(row_xml(3,['Section guide: Supplementary Information S8. S01 lists worksheet names and header rows for all 112 sections.'],2,32,False))
                    if sid==1:
                        emit(row_xml(5,['Block','Worksheet','Records','Header row','Columns'],3,30,False))
                        for r,vals in enumerate(catalog,6): emit(row_xml(r,vals,height=20))
                    for e in blocks:
                        s=e['start']; block=e['block']
                        title=block+' '+Path(e['file']).name.removesuffix('.gz').removesuffix('.csv').replace('_',' ')
                        note=('Input definitions and download code: '+INPUT_DEFINITIONS_URL if block=='S1.2' else
                              PARAMETER_NOTE if block in ('S17.7','S20.7') else 'Full numerical results are provided in this section.')
                        for r,txt,style,height in [(s,title,1,30),(s+1,note,2,44),(s+2,f"{e['rows']:,} records.",2,22)]:
                            emit(row_xml(r,[txt],style,height,False));merges.append(f'A{r}:E{r}')
                        emit(row_xml(e['header_row'],e['header'],3,numeric=False))
                        actual=0
                        with rows(e['path']) as reader:
                            require(next(reader)==e['header'],'Source header changed')
                            for actual,values in enumerate(reader,1):
                                require(len(values)==len(e['header']),'Ragged CSV row: '+e['file'])
                                emit(row_xml(e['header_row']+actual,display_values(block,e['header'],values)))
                        require(actual==e['rows'],'Workbook row count mismatch: '+block)
                    emit('</sheetData><mergeCells count="'+str(len(merges))+'">'+''.join('<mergeCell ref="'+r+'"/>' for r in merges)+'</mergeCells></worksheet>')
        for e in entries:
            require(sha(e['path'])==sources[e['file']]['sha256'],'Source changed during workbook export: '+e['file'])
        temp.replace(target)
        dump(root/'workbook_manifest.json',dict(workbook=target.name,sha256=sha(target),bytes=target.stat().st_size,
            reporting_version=VERSION,worksheets=20,blocks=len(entries),
            sections=[{k:e[k] for k in ['block','file','rows','sheet','header_row']} for e in entries]))
    finally:
        if temp.exists(): temp.unlink()
    return target


